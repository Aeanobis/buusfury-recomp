#!/usr/bin/env python3
"""Turns a screenshot of Buu's Fury's Equip screen into the backdrop the Legacy
of Goku II shop mod draws its outfit page on.

make_equip_backdrop.py SCREENSHOT.png OUT.inc

The screenshot (sprites/buusfury-equip-screen.png) was taken with
  ./buusfury --headless 400 --load-state games/buusfury/states/goku-snake-way.state \
      --input "N:60,S:4,N:80,r:4,N:60,r:4,N:80" --shot OUT.png
Everything that changes is wiped back to the striped background (the slot
names, the numbers, the speed row, the neighbouring page names, the cursor),
and the cursor arrow is saved separately so it can be drawn on any row.
"""
import struct
import sys
import zlib

W, H = 240, 160


def load(path):
    d = open(path, 'rb').read()
    i, idat = 8, b''
    while i < len(d):
        n = struct.unpack('>I', d[i:i + 4])[0]
        if d[i + 4:i + 8] == b'IDAT':
            idat += d[i + 8:i + 8 + n]
        i += 12 + n
    raw = zlib.decompress(idat)
    row = W * 3 + 1
    return [[tuple(raw[y * row + 1 + x * 3:y * row + 4 + x * 3]) for x in range(W)] for y in range(H)]


def main():
    im = load(sys.argv[1])
    ARROW = (2, 30, 17, 42)  # x0, y0, x1, y1
    arrow = [[im[y][x] for x in range(ARROW[0], ARROW[2])] for y in range(ARROW[1], ARROW[3])]
    below = [[im[y + 16][x] for x in range(ARROW[0], ARROW[2])] for y in range(ARROW[1], ARROW[3])]

    def wipe(x0, y0, x1, y1, clean_x):
        for y in range(y0, y1):
            for x in range(x0, x1):
                im[y][x] = im[y][clean_x]

    wipe(33, 30, 150, 92, 150)    # the four slot names
    wipe(193, 34, 236, 72, 150)   # the three numbers
    wipe(170, 72, 236, 86, 150)   # the speed row: no such stat here
    wipe(32, 9, 98, 24, 99)       # "Inventory"
    wipe(140, 9, 208, 24, 139)    # "Options"
    for y in range(ARROW[1], ARROW[3]):  # the cursor: the same strip one row down has none
        for x in range(ARROW[0], ARROW[2]):
            im[y][x] = im[y + 16][x]

    with open(sys.argv[2], 'w') as f:
        f.write('// Generated by tools/sprites/make_equip_backdrop.py from a screenshot of Buu\'s Fury\'s Equip screen. Do not edit.\n')
        f.write('// 0x00BBGGRR; in the arrow, 0xFFFFFFFF = see-through.\n')
        f.write('static const uint32_t equipBackdrop[240 * 160] = {')
        n = 0
        for y in range(H):
            for x in range(W):
                r, g, b = im[y][x]
                f.write(('\n\t' if n % 12 == 0 else ' ') + '0x%06X,' % (r | g << 8 | b << 16))
                n += 1
        f.write('\n};\n#define EQUIP_ARROW_X %d\n#define EQUIP_ARROW_Y %d\n#define EQUIP_ARROW_W %d\n#define EQUIP_ARROW_H %d\n' %
                (ARROW[0], ARROW[1], ARROW[2] - ARROW[0], ARROW[3] - ARROW[1]))
        f.write('static const uint32_t equipArrow[EQUIP_ARROW_W * EQUIP_ARROW_H] = {')
        n = 0
        for row, under in zip(arrow, below):
            for p, u in zip(row, under):
                r, g, b = p
                f.write(('\n\t' if n % 12 == 0 else ' ') + ('0xFFFFFFFF,' if p == u else '0x%06X,' % (r | g << 8 | b << 16)))
                n += 1
        f.write('\n};\n')


if __name__ == '__main__':
    main()
