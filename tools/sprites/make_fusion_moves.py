#!/usr/bin/env python3
"""Builds the pictures for the fusions' own attacks from frames captured out of Buu's Fury.

make_fusion_moves.py CAPTURE_DIR OUT.inc

CAPTURE_DIR holds, for each move NAME below, NAME_<f>.png for f = 0, 2, 4...: the
game's sprites only (--obj-only), f frames after the attack button went down,
with Goku standing in for the fused character facing right (see
capture_fusion_moves.sh). Everything to the right of him is the attack's effect.
Each frame is cut down to the box that has something in it and stored with
where that box is relative to his hand. icon_<id>.png are ordinary screenshots
with attack <id> selected, for the attack box's icon.
"""
import os
import struct
import sys
import zlib

W, H = 240, 160
PLAYER_X, PLAYER_FEET, HAND_UP = 124, 87, 17   # the middle of him, his feet, and how far up his hand is
EFFECT_LEFT = 131                              # nothing left of this is the attack
MOVES = (('ghost', 13), ('ball', 23))  # the held moves are in make_hold_moves.py  # capture name, Buu's Fury attack number
ICON = (10, 10, 26, 12)                        # the inside of Buu's Fury's attack box


def load(path):
    d = open(path, 'rb').read()
    i, idat = 8, b''
    while i < len(d):
        n = struct.unpack('>I', d[i:i + 4])[0]
        if d[i + 4:i + 8] == b'IDAT':
            idat += d[i + 8:i + 8 + n]
        i += 12 + n
    raw = zlib.decompress(idat)
    row = W * 3 + 1
    return [[tuple(raw[y * row + 1 + x * 3:y * row + 4 + x * 3]) for x in range(W)] for y in range(H)]


def main():
    src, out = sys.argv[1], sys.argv[2]
    palette, pixels, frames, moves, icons = [(0, 0, 0)], bytearray(), [], [], []
    index = {(0, 0, 0): 0}
    for name, attack in MOVES:
        first = len(frames)
        f = 0
        while os.path.exists(os.path.join(src, '%s_%d.png' % (name, f))):
            im = load(os.path.join(src, '%s_%d.png' % (name, f)))
            left = EFFECT_LEFT
            if name == 'ghost':
                # The ghost floats beside him, overlapping where Goku (who cannot do this
                # attack, and is drawn as garbage while he tries) stands. The ghost is the
                # only thing there in pale blue and white, so keep just those colours.
                left = 120
                for y in range(H):
                    for x in range(W):
                        r, g, b = im[y][x]
                        if not (b >= 200 and g >= 200 and r <= g and 58 <= y < 86 and 130 <= x < 150):  # (and only where the ghost is)
                            im[y][x] = (0, 0, 0)
            if name == 'bigbang':
                # The ball is charged at his hand, over his body: keep its cyan and
                # white there too (nothing of Goku is those colours)
                left = 118
                for y in range(H):
                    for x in range(left, EFFECT_LEFT):
                        r, g, b = im[y][x]
                        if not (b >= 200 and g >= 200 and r <= g):
                            im[y][x] = (0, 0, 0)
            pts = [(x, y) for y in range(8, H) for x in range(left, W) if im[y][x] != (0, 0, 0)]
            if pts:
                x0, x1 = min(p[0] for p in pts), max(p[0] for p in pts)
                y0, y1 = min(p[1] for p in pts), max(p[1] for p in pts)
                frames.append((f, x0 - PLAYER_X, y0 - (PLAYER_FEET - HAND_UP), x1 - x0 + 1, y1 - y0 + 1, len(pixels)))
                for y in range(y0, y1 + 1):
                    for x in range(x0, x1 + 1):
                        c = im[y][x]
                        if c not in index:
                            index[c] = len(palette)
                            palette.append(c)
                        pixels.append(index[c])
            f += 2
        moves.append((name, first, len(frames) - first))
        im = load(os.path.join(src, 'icon_%d.png' % attack))
        icons.append([im[y][x] for y in range(ICON[1], ICON[1] + ICON[3]) for x in range(ICON[0], ICON[0] + ICON[2])])
    assert len(palette) <= 256, len(palette)
    with open(out, 'w') as o:
        o.write('// Generated by tools/sprites/make_fusion_moves.py from frames captured out of Buu\'s Fury. Do not edit.\n')
        o.write('// A frame: when it shows (game frames after the button), where its box is relative to the\n')
        o.write('// character\'s hand when he faces right, its size, and where its pixels start. Pixel 0 is see-through.\n')
        o.write('#define FM_HAND_UP %d\n' % HAND_UP)
        o.write('static const uint32_t fmPalette[%d] = {' % len(palette))
        o.write(' '.join('0x%06X,' % (r | g << 8 | b << 16) for r, g, b in palette) + ' };\n')
        o.write('static const struct FmFrame { uint8_t at; int16_t x, y; uint8_t w, h; uint32_t pixels; } fmFrames[] = {\n')
        for fr in frames:
            o.write('\t{ %d, %d, %d, %d, %d, %d },\n' % fr)
        o.write('};\nenum { %s };\n' % ', '.join('FM_' + n.upper() for n, _, _ in moves))
        o.write('static const struct { uint16_t first, count; } fmMoves[] = { %s };\n' % ', '.join('{ %d, %d }' % (a, b) for _, a, b in moves))
        o.write('#define FM_ICON_W %d\n#define FM_ICON_H %d\nstatic const uint32_t fmIcons[%d][FM_ICON_W * FM_ICON_H] = {\n' % (ICON[2], ICON[3], len(icons)))
        for icon in icons:
            o.write('\t{ ' + ' '.join('0x%06X,' % (r | g << 8 | b << 16) for r, g, b in icon) + ' },\n')
        o.write('};\nstatic const uint8_t fmPixels[%d] = {' % len(pixels))
        for i, b in enumerate(pixels):
            o.write(('\n\t' if i % 32 == 0 else ' ') + '%d,' % b)
        o.write('\n};\n')
    print('%d frames, %d colours, %d bytes of pixels' % (len(frames), len(palette), len(pixels)))


if __name__ == '__main__':
    main()
