#!/usr/bin/env python3
"""Converts Buu's Fury portraits for use in Legacy of Goku II.

convert_portrait.py NAME ROM_OFFSET OUT.inc PREVIEW.png  BF:LG2FRAME:PALETTE ...

Each item makes one 64x64 portrait: Buu's Fury portrait number BF, recoloured to
a Legacy of Goku II palette ("master" for dialogue, "status" for the status
screen, which has its own), with the plain grey frame taken from Legacy of Goku
II portrait LG2FRAME in place of Buu's Fury's gold one. The portraits are
written one after another as uncompressed graphics blocks for ROM_OFFSET.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(__file__))
from sheet import write_png

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
LG2_TABLE, BF_TABLE = 0x6A981C, 0x6F395C
BF_FRAME = 5    # thickness of Buu's Fury's frame
LG2_FRAME = 2   # thickness of Legacy of Goku II's


def palette(name):
    raw = open(os.path.join(ROOT, 'sprites/palettes', name), 'rb').read()
    return [(c & 31, (c >> 5) & 31, (c >> 10) & 31) for c in struct.unpack_from('<256H', raw, 0)]


def nearest(src, dst):
    table = [0] * 256
    for i in range(256):
        r, g, b = src[i]
        table[i] = min(range(1, 256), key=lambda j: 3 * (dst[j][0] - r) ** 2 + 4 * (dst[j][1] - g) ** 2 + 2 * (dst[j][2] - b) ** 2)
    return bytes(table)


def main():
    name, offset, out, preview = sys.argv[1], int(sys.argv[2], 0), sys.argv[3], sys.argv[4]
    lrom = open(os.path.join(ROOT, 'build/lgoku2/rom.gba'), 'rb').read()
    brom = open(os.path.join(ROOT, 'build/buusfury/rom.gba'), 'rb').read()
    bf_pal = palette('buusfury-obj.bin')
    pals = {'master': palette('lgoku2-obj.bin'), 'status': palette('lgoku2-status-bg.bin')}
    tables = {k: nearest(bf_pal, v) for k, v in pals.items()}
    blob = bytearray()
    offsets = []
    shots = []
    for item in sys.argv[5:]:
        bf, lg, which = item.split(':')
        b = open(os.path.join(ROOT, 'build/sprites/bfportraits/%08X.bin' % struct.unpack_from('<I', brom, BF_TABLE + 4 * int(bf))[0]), 'rb').read()
        l = open(os.path.join(ROOT, 'build/sprites/lg2portraits/%08X.bin' % struct.unpack_from('<I', lrom, LG2_TABLE + 4 * int(lg))[0]), 'rb').read()
        b = b.translate(tables[which])
        fill = b[(BF_FRAME + 1) * 64 + BF_FRAME + 1]    # a background pixel, for the gap between the two frame sizes
        px = bytearray(4096)
        for y in range(64):
            for x in range(64):
                edge = min(x, y, 63 - x, 63 - y)
                if edge < LG2_FRAME:
                    px[y * 64 + x] = l[y * 64 + x]
                elif edge < BF_FRAME:
                    px[y * 64 + x] = fill
                else:
                    px[y * 64 + x] = b[y * 64 + x]
        offsets.append(len(blob))
        blob += struct.pack('<II', 0, 4096) + px
        shots.append((px, pals[which]))
    with open(out, 'w') as f:
        f.write('// Generated by tools/sprites/convert_portrait.py. Do not edit.\n#include <stdint.h>\n\n')
        f.write('const uint32_t %sRomOffset = 0x%X;\nconst uint32_t %sSize = %d;\n' % (name, offset, name, len(blob)))
        f.write('const uint32_t %sAt[] = { %s }; // offset of each portrait within the data\n' % (name, ', '.join(str(o) for o in offsets)))
        f.write('const uint8_t %sData[] = {' % name)
        for i, v in enumerate(blob):
            f.write(('\n\t' if i % 24 == 0 else ' ') + '0x%02X,' % v)
        f.write('\n};\n')
    k = 3
    W = len(shots) * (64 * k + 2)
    img = bytearray()
    for y in range(64):
        line = b''
        for px, pal in shots:
            line += b''.join(bytes((pal[px[y * 64 + x]][0] << 3, pal[px[y * 64 + x]][1] << 3, pal[px[y * 64 + x]][2] << 3)) * k for x in range(64)) + b'\xff\x00\xff' * 2
        img += line * k
    write_png(preview, img, W, 64 * k)
    print('%s: %d portraits, %d bytes at 0x%X' % (name, len(shots), len(blob), offset))


if __name__ == '__main__':
    main()
