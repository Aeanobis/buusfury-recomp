#!/usr/bin/env python3
"""Builds the pictures for the fusions' hold-B attacks from frames captured out of Buu's Fury.

make_hold_moves.py CAPTURE_DIR OUT.inc

CAPTURE_DIR holds NAME_<f>.png for f = 0, 2, 4, ... 238: the game's sprites only
(--obj-only), f frames after B went down, with B held for 180 frames and Goku
standing in for the fused character facing right (capture_fusion_moves.sh).
Each move has three parts: the lead-in, a stretch that repeats while B is held
(its period is found by comparing frames), and what happens when B is let go
(from frame 182 on). Frames are cut to the box with something in it and kept
relative to his hand. icon_<id>.png are screenshots with attack <id> selected.
"""
import os
import struct
import sys
import zlib

W, H = 240, 160
PLAYER_X, PLAYER_FEET, HAND_UP = 124, 87, 17
EFFECT_LEFT = 131
RELEASE = 182         # first captured frame after B went up
# name, attack number (for the icon), end of the lead-in, keep only cyan/white left of EFFECT_LEFT
MOVES = (('bigbang', 3, 28, True), ('dragon', 5, 100, False), ('lines', 1, 28, True), ('sword', 9, 60, True))
ICON = (10, 10, 26, 12)


def load(path):
    d = open(path, 'rb').read()
    i, idat = 8, b''
    while i < len(d):
        n = struct.unpack('>I', d[i:i + 4])[0]
        if d[i + 4:i + 8] == b'IDAT':
            idat += d[i + 8:i + 8 + n]
        i += 12 + n
    raw = zlib.decompress(idat)
    row = W * 3 + 1
    return [[tuple(raw[y * row + 1 + x * 3:y * row + 4 + x * 3]) for x in range(W)] for y in range(H)]


def effect(im, cyan_left):
    """The attack's pixels: everything right of the stand-in, and his hand's cyan/white."""
    left = 118 if cyan_left else EFFECT_LEFT
    for y in range(H):
        for x in range(0, EFFECT_LEFT):
            r, g, b = im[y][x]
            if x < left or not (b >= 200 and g >= 200 and r <= g and 40 <= y < 100):
                im[y][x] = (0, 0, 0)
    for y in range(H):
        for x in range(W):
            if y < 8:
                im[y][x] = (0, 0, 0)
    return im


def main():
    src, out = sys.argv[1], sys.argv[2]
    palette, pixels, frames, moves, icons = [(0, 0, 0)], bytearray(), [], [], []
    index = {(0, 0, 0): 0}
    for name, attack, lead, cyan_left in MOVES:
        first = len(frames)
        keys = {}
        for f in range(0, 240, 2):
            path = os.path.join(src, '%s_%d.png' % (name, f))
            if not os.path.exists(path):
                break
            im = effect(load(path), cyan_left)
            pts = [(x, y) for y in range(H) for x in range(W) if im[y][x] != (0, 0, 0)]
            if not pts:
                keys[f] = None
                continue
            x0, x1 = min(p[0] for p in pts), max(p[0] for p in pts)
            y0, y1 = min(p[1] for p in pts), max(p[1] for p in pts)
            block = bytearray()
            for y in range(y0, y1 + 1):
                for x in range(x0, x1 + 1):
                    c = im[y][x]
                    if c not in index:
                        index[c] = len(palette)
                        palette.append(c)
                    block.append(index[c])
            keys[f] = (x0, y0, x1 - x0 + 1, y1 - y0 + 1, bytes(block))
            frames.append((f, x0 - PLAYER_X, y0 - (PLAYER_FEET - HAND_UP), x1 - x0 + 1, y1 - y0 + 1, len(pixels)))
            pixels += block
        # the period of the held stretch: the smallest step at which frames repeat
        held = [f for f in range(lead, RELEASE, 2) if keys.get(f)]
        period = 0
        for p in range(2, 80, 2):
            same = sum(1 for f in held if f + p < RELEASE and keys.get(f + p) and keys[f][:4] == keys[f + p][:4] and keys[f][4] == keys[f + p][4])
            if same >= len(held) * 0.9 - 3:
                period = p
                break
        hold_from = next((i for i, fr in enumerate(frames[first:]) if fr[0] >= lead), 0)
        release = next((i for i, fr in enumerate(frames[first:]) if fr[0] >= RELEASE), len(frames) - first)
        moves.append((name, first, len(frames) - first, hold_from, release, period))
        print('%s: %d frames; lead-in to %d, held part repeats every %d frames, let go at %d' % (name, len(frames) - first, lead, period, RELEASE))
        im = load(os.path.join(src, 'icon_%d.png' % attack))
        icons.append([im[y][x] for y in range(ICON[1], ICON[1] + ICON[3]) for x in range(ICON[0], ICON[0] + ICON[2])])
    assert len(palette) <= 256, len(palette)
    with open(out, 'w') as o:
        o.write('// Generated by tools/sprites/make_hold_moves.py from frames captured out of Buu\'s Fury. Do not edit.\n')
        o.write('#define HM_HAND_UP %d\n' % HAND_UP)
        o.write('static const uint32_t hmPalette[%d] = {' % len(palette))
        o.write(' '.join('0x%06X,' % (r | g << 8 | b << 16) for r, g, b in palette) + ' };\n')
        o.write('// when it shows (game frames after B), its box relative to the hand facing right, size, pixel start\n')
        o.write('static const struct HmFrame { uint8_t at; int16_t x, y; uint8_t w, h; uint32_t pixels; } hmFrames[] = {\n')
        for fr in frames:
            o.write('\t{ %d, %d, %d, %d, %d, %d },\n' % fr)
        o.write('};\nenum { %s };\n' % ', '.join('HM_' + n.upper() for n, *_ in moves))
        o.write('// first frame, count, index where the held part begins, index of the first let-go frame, period of the held part\n')
        o.write('static const struct { uint16_t first, count, holdFrom, release, period; } hmMoves[] = { %s };\n' %
                ', '.join('{ %d, %d, %d, %d, %d }' % m[1:] for m in moves))
        o.write('#define HM_ICON_W %d\n#define HM_ICON_H %d\nstatic const uint32_t hmIcons[%d][HM_ICON_W * HM_ICON_H] = {\n' % (ICON[2], ICON[3], len(icons)))
        for icon in icons:
            o.write('\t{ ' + ' '.join('0x%06X,' % (r | g << 8 | b << 16) for r, g, b in icon) + ' },\n')
        o.write('};\nstatic const uint8_t hmPixels[%d] = {' % len(pixels))
        for i, b in enumerate(pixels):
            o.write(('\n\t' if i % 32 == 0 else ' ') + '%d,' % b)
        o.write('\n};\n')
    print('%d frames, %d colours, %d bytes of pixels' % (len(frames), len(palette), len(pixels)))


if __name__ == '__main__':
    main()
