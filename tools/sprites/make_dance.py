#!/usr/bin/env python3
"""Writes one animation of a Buu's Fury sprite as plain pictures a mod can draw over the screen.
make_dance.py NAME BF_DEF ANIM OUT.inc [DIRECTION]
Used for the fusion dance (animation 21), shown when the partner appears. The
direction (0 down, 1 up, 2 left, 3 right; default 3) is the side view, so the
two can face each other (the one on the right is drawn mirrored).
Each frame is CELL x CELL, 0x00BBGGRR with 0xFFFFFFFF for see-through; the feet are at (CELL/2, CELL-4)."""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import bf_defs
import contact
from sheet import load_palette

ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
CELL = 48
KEY = (1, 2, 3)


def main():
    name, number, anim, out = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
    direction = int(sys.argv[5]) if len(sys.argv) > 5 else 3
    exdir = os.path.join(ROOT, 'build/sprites/bf')
    frames = bf_defs.parse(open(os.path.join(ROOT, 'build/buusfury/rom.gba'), 'rb').read())[number]['anims'][anim][direction]
    pal = load_palette(os.path.join(exdir, 'objpalette.bin'))
    contact.SCALE = 1
    with open(out, 'w') as f:
        f.write('// Generated by tools/sprites/make_dance.py from Buu\'s Fury sprite %d, animation %d. Do not edit.\n' % (number, anim))
        f.write('#define %s_FRAMES %d\n#define %s_CELL %d\nstatic const uint32_t %s[%d][%d] = {\n' % (name.upper(), len(frames), name.upper(), CELL, name, len(frames), CELL * CELL))
        for fr in frames:
            img = bytearray(bytes(KEY) * (CELL * CELL))
            contact.draw_frame(img, CELL, CELL // 2 - 8, CELL - 4, 'bf', fr, exdir, pal)
            f.write('\t{')
            for i in range(CELL * CELL):
                r, g, b = img[i * 3:i * 3 + 3]
                f.write(('\n\t\t' if i % 12 == 0 else ' ') + ('0xFFFFFFFF,' if (r, g, b) == KEY else '0x%06X,' % (r | g << 8 | b << 16)))
            f.write('\n\t},\n')
        f.write('};\n')


if __name__ == '__main__':
    main()
